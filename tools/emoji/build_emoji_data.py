#!/usr/bin/env python3
"""
Builds src/Yaparr/Chat/Emoji/emoji.tsv, the emoji that reactions can use, with their names and search words.

Inputs (from unicode.org; not kept in the repository, they are large):
  emoji-test.txt   https://www.unicode.org/Public/emoji/latest/emoji-test.txt              (the emoji, their groups and the version that added them)
  en.xml           https://raw.githubusercontent.com/unicode-org/cldr/release-49/common/annotations/en.xml          (CLDR names and keywords)
  en-derived.xml   https://raw.githubusercontent.com/unicode-org/cldr/release-49/common/annotationsDerived/en.xml   (the same for sequences, flags and so on)

Usage: build_emoji_data.py <folder with the three files> <output file> [max emoji version, default 13.1]

Only emoji that are fully qualified, not skin tone variants (any of the five tones is accepted on receipt, see EmojiData) and not
newer than the chosen version are written. Newer emoji are shown as an empty box by computers and phones whose emoji font is older, so the
set is held back; raise the version when the oldest system Yaparr runs on has caught up.

Output: lines starting with '#' are comments; '@Name' starts a group; every other line is: emoji TAB name TAB keywords (separated by '|').
"""
import re
import sys
import xml.etree.ElementTree as ET

VS16 = "\ufe0f"
TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}


def strip(s):
    return s.replace(VS16, "")


def annotations(path):
    names, words = {}, {}
    for a in ET.parse(path).getroot().iter("annotation"):
        cp = strip(a.attrib["cp"])
        text = (a.text or "").strip()
        if a.attrib.get("type") == "tts":
            names[cp] = text
        else:
            words[cp] = [w.strip() for w in text.split("|") if w.strip()]
    return names, words


def main():
    folder, out = sys.argv[1], sys.argv[2]
    max_version = tuple(int(x) for x in (sys.argv[3] if len(sys.argv) > 3 else "13.1").split("."))
    names, words = annotations(f"{folder}/en.xml")
    n2, w2 = annotations(f"{folder}/en-derived.xml")
    for k, v in n2.items(): names.setdefault(k, v)
    for k, v in w2.items(): words.setdefault(k, v)

    line_re = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+)\.(\d+)\s+(.*)$")
    groups, order, group = {}, [], None
    version_seen, total = "", 0
    for line in open(f"{folder}/emoji-test.txt", encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        if line.startswith("# Version:"):
            version_seen = line.split(":", 1)[1].strip()
        m = line_re.match(line)
        if not m or group in (None, "Component"):
            continue
        emoji = m.group(2)
        if any(ch in TONES for ch in emoji):
            continue
        if (int(m.group(3)), int(m.group(4))) > max_version:
            continue
        key = strip(emoji)
        name = names.get(key) or m.group(5)
        kw = [w for w in words.get(key, []) if w.lower() != name.lower()]
        if group not in groups:
            groups[group] = []
            order.append(group)
        groups[group].append((emoji, name, kw))
        total += 1

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Yaparr emoji data: the emoji that reactions can use, with names and search words.\n")
        f.write(f"# Generated by tools/emoji/build_emoji_data.py from Unicode emoji {version_seen} (held back to {'.'.join(map(str, max_version))}) and CLDR 49 (English).\n")
        f.write("# Unicode data files and software, Copyright 1991-2026 Unicode, Inc., used under the Unicode License v3 (https://www.unicode.org/license.txt).\n")
        f.write("# '@Name' starts a group; every other line is: emoji TAB name TAB keywords separated by '|'.\n")
        for g in order:
            f.write(f"@{g}\n")
            for emoji, name, kw in groups[g]:
                f.write(f"{emoji}\t{name}\t{'|'.join(kw)}\n")
    print(f"{total} emoji in {len(order)} groups -> {out}")


main()
